func TestTaskFetchRedirectKeepsCredentialHeadersOnOrigin(t *testing.T) {
	service.InitHttpClient()
	fetchSettings := system_setting.GetFetchSetting()
	previousSettings := *fetchSettings
	fetchSettings.AllowPrivateIp = true
	fetchSettings.AllowedPorts = []string{"1-65535"}
	t.Cleanup(func() { *fetchSettings = previousSettings })

	originHeaders := make(chan http.Header, 2)
	targetHeaders := make(chan http.Header, 1)
	target := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		targetHeaders <- r.Header.Clone()
		w.WriteHeader(http.StatusOK)
	}))
	t.Cleanup(target.Close)
	origin := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		originHeaders <- r.Header.Clone()
		http.Redirect(w, r, target.URL+"/result", http.StatusTemporaryRedirect)
	}))
	t.Cleanup(origin.Close)
	info := &relaycommon.RelayInfo{ChannelMeta: &relaycommon.ChannelMeta{
		ApiKey: "saved-secret", HeadersOverride: map[string]any{"X-Vendor-Credential": "{api_key}"},
	}}

	get, err := http.NewRequest(http.MethodGet, origin.URL+"/task", nil)
	require.NoError(t, err)
	get.Header.Set("Authorization", "Bearer saved-secret")
	get.Header.Set("X-API-Key", "saved-secret")
	get.Header.Set("Accept", "application/json")
	response, err := DoTaskFetchRequest(get, "", info)
	require.NoError(t, err)
	require.NoError(t, response.Body.Close())
	require.Equal(t, http.StatusOK, response.StatusCode)
	assert.Equal(t, "saved-secret", (<-originHeaders).Get("X-Vendor-Credential"))
	require.Len(t, targetHeaders, 1)
	forwarded := <-targetHeaders
	assert.Empty(t, forwarded.Get("Authorization"))
	assert.Empty(t, forwarded.Get("X-API-Key"))
	assert.Empty(t, forwarded.Get("X-Vendor-Credential"))
	assert.Equal(t, "application/json", forwarded.Get("Accept"))

	post, err := http.NewRequest(http.MethodPost, origin.URL+"/task", strings.NewReader("private task data"))
	require.NoError(t, err)
	response, err = DoTaskFetchRequest(post, "", info)
	if response != nil {
		_, _ = io.Copy(io.Discard, response.Body)
		_ = response.Body.Close()
	}
	require.ErrorContains(t, err, "cannot replay a body")
	require.Len(t, originHeaders, 1)
	assert.Empty(t, targetHeaders)
}

